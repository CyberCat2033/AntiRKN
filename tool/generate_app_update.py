#!/usr/bin/env python3
"""Generate the signed application update contract from its single schema."""
import json
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
schema = json.loads((ROOT / 'schemas/app-update-v1.json').read_text())


def strings(values):
    return '{' + ', '.join(quote(v) for v in values) + '}'


def quote(value):
    if "'" in value or '\\' in value or '$' in value:
        raise SystemExit('Value cannot be a plain Dart string: ' + value)
    return "'" + value + "'"


def raw(pattern):
    if "'" in pattern:
        raise SystemExit('Pattern cannot be a raw Dart string')
    return "r'" + pattern + "'"


def camel(wire):
    head, *rest = wire.split('-')
    return head + ''.join(part[:1].upper() + part[1:] for part in rest)


def pascal(name):
    return name[:1].upper() + name[1:]


kinds = schema['kinds']
lines = [
    '// Generated by tool/generate_app_update.py; do not edit.',
    '// Source: schemas/app-update-v1.json',
    "import 'dart:convert';",
    '',
    f"const appUpdateSchemaVersion = {schema['version']};",
    f"const appUpdateFormat = {quote(schema['format'])};",
    f"const appUpdateSignaturePrefix = {quote(schema['signaturePrefix'])};",
    f"const appUpdateAppId = {quote(schema['appId'])};",
    f"const appUpdateChannels = {strings(schema['channels'])};",
    f"const appUpdateManifestMaxBytes = {schema['manifestMaxBytes']};",
    f"const appUpdateMaxSignatures = {schema['maxSignatures']};",
    f"final appUpdateKeyId = RegExp({raw(schema['keyIdPattern'])});",
    f"const appUpdateManifestUrl = {raw(schema['manifestUrl'])};",
    f"const appUpdateArtifactUrlPrefix = {quote(schema['artifactUrlPrefix'])};",
    f"const appUpdateRepositoryPath = {quote(schema['repositoryPath'])};",
    f"const appUpdateRedirectHosts = {strings(schema['redirectHosts'])};",
    f"const appUpdateInstallKindFile = {quote(schema['installKindFile'])};",
    f"const appUpdateAndroidOnly = {strings(schema['androidOnly'])};",
    'const appUpdateAndroidAbiIds = <String, int>{'
    + ', '.join(f"{quote(k)}: {v}" for k, v in schema['androidAbiIds'].items()) + '};',
    '',
    '/// Package kinds; [wire] is the manifest and install-kind marker value.',
    'enum AppUpdateKind {',
]
lines += [f'{camel(kind)}({quote(kind)}),' for kind in kinds]
lines[-1] = lines[-1][:-1] + ';'
lines += [
    'const AppUpdateKind(this.wire);',
    'final String wire;',
    'bool get isAndroid => this == '
    f"AppUpdateKind.{camel(schema['androidKind'])};",
    'static AppUpdateKind? parse(Object? value) {',
    'for (final kind in values) { if (kind.wire == value) return kind; }',
    'return null;',
    '}',
    '}',
    '',
    'const appUpdateKindArches = <AppUpdateKind, Set<String>>{',
]
lines += [f'AppUpdateKind.{camel(kind)}: {strings(arches)},' for kind, arches in kinds.items()]
lines += ['};', '']

regexes = []


def parser(owner, name, rule):
    kind = rule['type']
    source = f"map['{name}']"
    if kind == 'kind':
        return f"AppUpdateKind.parse({source}) ?? (throw const FormatException(_invalid))"
    if kind == 'artifacts':
        return (f"_appUpdateList({source}, {rule['minItems']}, {rule['maxItems']})"
                '.map(AppUpdateArtifact.fromJson).toList(growable: false)')
    if kind == 'changelog':
        return f"_appUpdateChangelog({source})"
    if kind == 'integer':
        if 'enum' in rule:
            return f"_appUpdateInt({source}, {min(rule['enum'])}, {max(rule['enum'])})"
        return f"_appUpdateInt({source}, {rule['minimum']}, {rule['maximum']})"
    if kind == 'string':
        args = [source]
        if 'enum' in rule:
            args.append(f"values: const {strings(rule['enum'])}")
        if 'pattern' in rule:
            regex = f'_appUpdate{owner}{pascal(name)}'
            regexes.append(f"final {regex} = RegExp({raw(rule['pattern'])});")
            args.append(f'pattern: {regex}')
        args.append(f"maxLength: {rule.get('maxLength', 256)}")
        return f"_appUpdateString({', '.join(args)})"
    raise SystemExit('Unknown field type: ' + kind)


def dart_type(rule):
    base = {'integer': 'int', 'string': 'String', 'kind': 'AppUpdateKind',
            'artifacts': 'List<AppUpdateArtifact>',
            'changelog': 'Map<String, List<AppUpdateChangelogEntry>>'}[rule['type']]
    return base + ('?' if rule.get('optional') else '')


def serializer(name, rule):
    value = name
    if rule['type'] == 'kind':
        value = f'{name}.wire'
    elif rule['type'] == 'artifacts':
        value = f'[for (final item in {name}) item.toJson()]'
    elif rule['type'] == 'changelog':
        value = (f'{{for (final e in {name}.entries) '
                 'e.key: [for (final item in e.value) item.toJson()]}')
    if rule.get('optional'):
        return f"if ({name} != null) '{name}': {name},"
    return f"'{name}': {value},"


def model(owner, fields, doc):
    required = [name for name, rule in fields.items() if not rule.get('optional')]
    result = [f'/// {doc}', f'final class AppUpdate{owner} {{', f'const AppUpdate{owner}({{']
    result += [('' if rule.get('optional') else 'required ') + f'this.{name},'
               for name, rule in fields.items()]
    result += ['});']
    result += [f'final {dart_type(rule)} {name};' for name, rule in fields.items()]
    result += [
        '',
        "/// Strict: unknown, missing or out-of-range fields throw 'update_manifest_invalid'.",
        f'factory AppUpdate{owner}.fromJson(Object? value) {{',
        f'final map = _appUpdateObject(value, const {strings(fields)}, const {strings(required)});',
        f'return AppUpdate{owner}(',
    ]
    for name, rule in fields.items():
        source = parser(owner, name, rule)
        if rule.get('optional'):
            source = f"map.containsKey('{name}') ? {source} : null"
        result.append(f'{name}: {source},')
    result += [');', '}', '', 'Map<String, Object?> toJson() => {']
    result += [serializer(name, rule) for name, rule in fields.items()]
    result += ['};', '}', '']
    return result


changelog = schema['changelog']
lines += [
    f"const appUpdateChangelogLanguages = {strings(changelog['languages'])};",
    f"const appUpdateChangelogMaxItems = {changelog['maxItems']};",
    f"const appUpdateChangelogMaxBytes = {changelog['maxBytesPerLanguage']};",
    '',
]
body = model('ChangelogEntry', schema['changelogEntry'],
             'One released version of a CHANGELOG file.')
body += model('Artifact', schema['artifact'], 'One downloadable release file.')
body += model('Payload', schema['payload'], 'The signed release description.')
lines += body + regexes + ['', '''
const _invalid = 'update_manifest_invalid';

Map<String, Object?> _appUpdateObject(
  Object? value,
  Set<String> allowed,
  Set<String> required,
) {
  if (value is! Map<String, Object?> ||
      !value.keys.every(allowed.contains) ||
      !required.every(value.containsKey)) {
    throw const FormatException(_invalid);
  }
  return value;
}

List<Object?> _appUpdateList(Object? value, int min, int max) {
  if (value is! List<Object?> || value.length < min || value.length > max) {
    throw const FormatException(_invalid);
  }
  return value;
}

/// Every language present, at most the item and byte limits per language.
Map<String, List<AppUpdateChangelogEntry>> _appUpdateChangelog(Object? value) {
  final map = _appUpdateObject(
    value,
    appUpdateChangelogLanguages,
    appUpdateChangelogLanguages,
  );
  return Map.unmodifiable({
    for (final language in appUpdateChangelogLanguages)
      language: () {
        final items = _appUpdateList(
          map[language],
          1,
          appUpdateChangelogMaxItems,
        ).map(AppUpdateChangelogEntry.fromJson).toList(growable: false);
        final bytes = items.fold<int>(
          0,
          (sum, item) => sum + utf8.encode(item.markdown).length,
        );
        if (bytes > appUpdateChangelogMaxBytes) {
          throw const FormatException(_invalid);
        }
        return items;
      }(),
  });
}

int _appUpdateInt(Object? value, int min, int max) {
  if (value is! int || value < min || value > max) {
    throw const FormatException(_invalid);
  }
  return value;
}

String _appUpdateString(
  Object? value, {
  Set<String>? values,
  RegExp? pattern,
  required int maxLength,
}) {
  if (value is! String ||
      value.length > maxLength ||
      (values != null && !values.contains(value)) ||
      (pattern != null && !pattern.hasMatch(value))) {
    throw const FormatException(_invalid);
  }
  return value;
}
''']
source = '\n'.join(lines) + '\n'
with tempfile.TemporaryDirectory() as directory:
    temporary = Path(directory) / 'contract.dart'
    temporary.write_text(source)
    subprocess.run(['dart', 'format', str(temporary)], check=True, capture_output=True)
    source = temporary.read_text()
target = ROOT / 'packages/domain/lib/src/app_update_contract.g.dart'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != source:
        raise SystemExit('Generated file differs: ' + str(target.relative_to(ROOT)))
else:
    target.write_text(source)
print('App update generated contract: OK')
