#!/usr/bin/env python3
"""Generate the cloud snapshot v5 contract from its single schema."""
import json
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
schema = json.loads((ROOT / 'schemas/cloud-snapshot-v5.json').read_text())
defs = schema['$defs']


def strings(values):
    return '{' + ', '.join("'" + v + "'" for v in values) + '}'


def raw(pattern):
    if "'" in pattern:
        raise SystemExit('Pattern cannot be a raw Dart string')
    return "r'" + pattern + "'"


author = schema['properties']['author']
document_id = schema['properties']['documents']['items']['properties']['id']
record = defs['vpnServerRecord']
lines = [
    '// Generated by tool/generate_snapshot.py; do not edit.',
    '// Source: schemas/cloud-snapshot-v5.json',
    f"const cloudSnapshotVersion = {schema['version']};",
    'const cloudSnapshotReadableVersions = {'
    + ', '.join(str(v) for v in schema['readableVersions']) + '};',
    f"const cloudSnapshotMaxRecords = {schema['maxRecords']};",
    f"const cloudSnapshotKeys = {strings(schema['required'])};",
    f"const cloudSnapshotAuthorKeys = {strings(author['properties'])};",
    'const cloudSnapshotAuthorNameMax = '
    f"{author['properties']['deviceName']['maxLength']};",
    f"final cloudSnapshotDocumentId = RegExp({raw(document_id['pattern'])});",
    f"const cloudServerCache = {strings(defs['serverProfile']['x-localCache'])};",
    f"const cloudVpnServerCache = {strings(record['x-localCache'])};",
    'const cloudVpnServerCacheWhenSettled = '
    f"{strings(record['x-localCacheWhenSettled'])};",
    'const cloudVpnServerCacheWhenTerminal = '
    f"{strings(record['x-localCacheWhenTerminal'])};",
    f"const cloudVpnProfileKeep = {strings(defs['vpnProfile']['x-keep'])};",
    f"const cloudRunnerKeep = {strings(defs['runnerJournal']['x-keep'])};",
    'const cloudRunnerUnfinished = '
    f"{strings(defs['runnerJournal']['x-unfinished'])};",
    'final cloudLocalDocument = RegExp('
    f"{raw('|'.join(defs['localDocuments']['x-patterns']))});",
]
source = '\n'.join(lines) + '\n'
with tempfile.TemporaryDirectory() as directory:
    temporary = Path(directory) / 'contract.dart'
    temporary.write_text(source)
    subprocess.run(['dart', 'format', str(temporary)], check=True, capture_output=True)
    source = temporary.read_text()
target = ROOT / 'packages/storage/lib/src/cloud_snapshot_contract.g.dart'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != source:
        raise SystemExit('Generated cloud snapshot contract differs')
else:
    target.write_text(source)
print('Cloud snapshot generated contract: OK')
