#!/usr/bin/env python3
"""Generate the versioned local journal header from its single schema."""
import json
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
schema = json.loads((ROOT / 'schemas/local-change-v2.json').read_text())
types = {'id': 'String', 'nullableId': 'String?', 'entityId': 'String',
         'kind': 'ChangeEntityKind', 'positive': 'int', 'nonnegative': 'int',
         'boolean': 'bool'}
fields = schema['fields']
lines = ["// Generated by tool/generate_changes.py; do not edit.",
         f"const localChangeSchemaVersion = {schema['version']};",
         'enum ChangeEntityKind { ' + ', '.join(schema['entityKinds']) + ' }',
         'final class ChangeHeader {', 'ChangeHeader({']
lines += [f'required this.{name},' for name in fields]
lines += ['this.schemaVersion = 1, List<String> mergeParents = const [],',
          '}) : mergeParents = List.unmodifiable(mergeParents) {',
          f"if (![1, 2].contains(schemaVersion) || (schemaVersion == 1 && mergeParents.isNotEmpty) || mergeParents.length > {schema['extensionFields']['mergeParents']['maxItems']} || mergeParents.toSet().length != mergeParents.length || mergeParents.any((id) => !_id(id) || id == changeId || id == baseChangeId) || (mergeParents.isNotEmpty && baseChangeId == null) || baseChangeId == changeId) {{ throw const FormatException('change_invalid'); }}"]
for name, kind in fields.items():
    invalid = {
        'id': f'!_id({name})',
        'nullableId': f'({name} != null && !_id({name}!))',
        'entityId': f'{name}.isEmpty || {name}.length > 256 || {name}.contains(RegExp(r"[\\x00-\\x1f\\x7f]"))',
        'positive': f'{name} < 1 || {name} > 9007199254740991',
        'nonnegative': f'{name} < 0 || {name} > 9007199254740991',
    }.get(kind)
    if invalid:
        lines += [f"if ({invalid}) {{ throw const FormatException('change_invalid'); }}"]
lines += ["if (revision != baseRevision + 1 || (baseRevision == 0) != (baseChangeId == null) || transactionIndex >= transactionSize) { throw const FormatException('change_invalid'); }", '}',
          "static bool _id(String value) => RegExp(r'^[a-f0-9]{32}$').hasMatch(value) && value.length == 32;"]
lines += [f'final {types[kind]} {name};' for name, kind in fields.items()]
lines += ['final int schemaVersion;', 'final List<String> mergeParents;', 'List<String> get parents => [?baseChangeId, ...mergeParents];']
lines += ['factory ChangeHeader.fromJson(Map<String, dynamic> value) {',
          "if (![1, localChangeSchemaVersion].contains(value['version'])) { throw const FormatException('change_version'); }",
          f"if (value.length != ({len(fields) + 1} + (value['version'] == 2 ? 1 : 0))) {{ throw const FormatException('change_invalid'); }}",
          'return ChangeHeader(', "schemaVersion: value['version'] as int,", "mergeParents: value['version'] == 2 ? List<String>.from(value['mergeParents'] as List) : const [],"]
for name, kind in fields.items():
    source = f"value['{name}']"
    if kind == 'kind':
        source = f'ChangeEntityKind.values.byName({source} as String)'
    else:
        source += f' as {types[kind]}'
    lines += [f'{name}: {source},']
lines += [');', '}', 'Map<String, Object?> toJson() => {', "'version': schemaVersion,", "if (schemaVersion == 2) 'mergeParents': mergeParents,"]
lines += [f"'{name}': {name}" + ('.name' if kind == 'kind' else '') + ',' for name, kind in fields.items()]
lines += ['};', '}']
with tempfile.TemporaryDirectory() as directory:
    temporary = Path(directory) / 'contract.dart'
    temporary.write_text('\n'.join(lines) + '\n')
    subprocess.run(['dart', 'format', str(temporary)], check=True, capture_output=True)
    source = temporary.read_text()
target = ROOT / 'packages/domain/lib/src/change_contract.g.dart'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != source:
        raise SystemExit('Generated file differs: ' + str(target.relative_to(ROOT)))
else:
    target.write_text(source)
print('Local change generated contract: OK')
