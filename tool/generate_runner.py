#!/usr/bin/env python3
"""Reproducible Dart/Python contract and bundled, hashed runner sources."""
import base64
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
schema = json.loads((ROOT / 'schemas/runner-v1.json').read_text())
encoded = json.dumps(schema, sort_keys=True, separators=(',', ':'))
files = {}
files['server/runner/contract.py'] = '''# Generated by tool/generate_runner.py; do not edit.
import json
import re
SCHEMA = json.loads(%r)

def validate_request(value):
    if type(value) is not dict:
        raise ValueError('invalid')
    if value.get('version') != SCHEMA['version']:
        raise ValueError('incompatible')
    spec = SCHEMA['request']
    if type(value.get('action')) is not str:
        raise ValueError('invalid')
    fields = spec['actions'].get(value.get('action'))
    if value.get('action') == 'submit':
        fields = spec['submissions'].get(value.get('kind'))
    if fields is None or set(value) != set(fields):
        raise ValueError('invalid')
    for key, entry in value.items():
        rule = spec['properties'][key]
        kind = int if rule['type'] == 'integer' else str
        if type(entry) is not kind:
            raise ValueError('invalid')
        if 'enum' in rule and entry not in rule['enum']:
            raise ValueError('invalid')
        if 'pattern' in rule and re.fullmatch(rule['pattern'], entry) is None:
            raise ValueError('invalid')
        if 'minimum' in rule and not rule['minimum'] <= entry <= rule['maximum']:
            raise ValueError('invalid')
        if 'maxLength' in rule and len(entry) > rule['maxLength']:
            raise ValueError('invalid')
    if 'port' in value and value['port'] < 1024 and not (value['action'] == 'panel_plan' and value['port'] == 0):
        raise ValueError('invalid')
    for key, expected in spec.get('kindConstants', {}).get(value.get('kind'), {}).items():
        if value.get(key) != expected:
            raise ValueError('invalid')
    return value
''' % encoded
files['packages/domain/lib/src/runner_contract.g.dart'] = '''// Generated by tool/generate_runner.py; do not edit.
import 'dart:convert';
final Map<String, dynamic> runnerSchema = jsonDecode(r\'''%s\''') as Map<String, dynamic>;
void validateRunnerRequest(Map<String, Object?> value) {
  final spec = runnerSchema['request'] as Map;
  final fields = (value['action'] == 'submit'
      ? (spec['submissions'] as Map)[value['kind']]
      : (spec['actions'] as Map)[value['action']]) as List?;
  if (value['version'] != runnerSchema['version'] || fields == null ||
      value.length != fields.length || !fields.every(value.containsKey)) {
    throw const FormatException('invalid_runner_request');
  }
  if (value['port'] case final int port) {
    if (port < 1024 && !(value['action'] == 'panel_plan' && port == 0)) {
      throw const FormatException('invalid_runner_port');
    }
  }
  final constants = (spec['kindConstants'] as Map)[value['kind']] as Map?;
  if (constants != null && !constants.entries.every((e) => value[e.key] == e.value)) {
    throw const FormatException('invalid_runner_constants');
  }
  for (final entry in value.entries) {
    final rule = (spec['properties'] as Map)[entry.key] as Map;
    final v = entry.value;
    if (rule['type'] == 'integer' ? v is! int : v is! String) {
      throw const FormatException('invalid_runner_type');
    }
    if (rule['enum'] case final List choices) {
      if (!choices.contains(v)) { throw const FormatException('invalid_runner_enum'); }
    }
    if (rule['pattern'] case final String pattern) {
      final match = RegExp(pattern).firstMatch(v as String);
      if (match == null || match.end != v.length) { throw const FormatException('invalid_runner_id'); }
    }
    if (rule['minimum'] case final int minimum) {
      if ((v as int) < minimum || v > (rule['maximum'] as int)) {
        throw const FormatException('invalid_runner_range');
      }
    }
    if (rule['maxLength'] case final int maximum) {
      if ((v as String).length > maximum) { throw const FormatException('invalid_runner_size'); }
    }
  }
}
''' % encoded

component_lock = json.loads((ROOT / 'schemas/component-releases.json').read_text())
verified = {k: v['version'] for k, v in component_lock.items()}
panel_update_lock = json.loads((ROOT / 'schemas/panel-update-release.json').read_text())
verified.update(panel=panel_update_lock['panelVersion'], xray=panel_update_lock['xrayVersion'])
verified['amneziawgTools'] = component_lock['amneziawg']['toolsVersion']
files['packages/domain/lib/src/runner_contract.g.dart'] += '\nconst verifiedComponentVersions = <String, String>' + json.dumps(verified) + ';\n'

def render(path, source):
    data = source.encode()
    if path.endswith('.dart'):
        # Use SDK formatter without writing into the worktree in --check mode.
        import tempfile
        with tempfile.TemporaryDirectory() as directory:
            temp = Path(directory) / 'generated.dart'
            temp.write_bytes(data)
            subprocess.run(['dart', 'format', str(temp)], check=True, capture_output=True)
            data = temp.read_bytes()
    dest = ROOT / path
    if '--check' in sys.argv:
        if not dest.exists() or dest.read_bytes() != data:
            raise SystemExit(f'Generated file differs: {path}')
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
    return data

contract = None
for path, source in files.items():
    data = render(path, source)
    if path.endswith('contract.py'):
        contract = data
# Bundle creation is enabled once the executable sources are present.
release_source = 'RELEASE = ' + repr(json.loads((ROOT / 'schemas/panel-release.json').read_text())) + '\n'
render('server/runner/panel_release.py', '# Generated by tool/generate_runner.py; do not edit.\n' + release_source)
component_source = 'RELEASES = ' + repr(json.loads((ROOT / 'schemas/component-releases.json').read_text())) + '\n'
render('server/runner/component_releases.py', '# Generated by tool/generate_runner.py; do not edit.\n' + component_source)
render('server/runner/panel_update_release.py', '# Generated by tool/generate_runner.py; do not edit.\nUPDATE_RELEASE = ' + repr(panel_update_lock) + '\n')
render('server/runner/xray_upgrade_release.py', '# Generated by tool/generate_runner.py; do not edit.\nTARGET = ' + repr(json.loads((ROOT / 'schemas/xray-upgrade-release.json').read_text())) + '\n')
paths = ['sysutil.py', 'upgrade_probe.py', 'component_upgrade.py', 'client_egress.py', 'egress_config.py', 'egress_network.py', 'egress_probe.py', 'egress_access.py', 'server_reboot.py','xray_transaction.py','xray_upgrade_release.py', 'connectivity_probe.py', 'managed_existing.py', 'managed_vless.py', 'managed_awg.py', 'managed_tt.py', 'inbound_remove.py', 'panel_clients.py', 'ssh_harden.py', 'protocol_remove.py', 'client_revocations.py', 'tt.py', 'tt_common.py', 'tt_external.py', 'tt_certificates.py', 'tt_contract.py', 'tt_tomli_parser.py', 'tt_tomli_re.py', 'tt_tomli_types.py', 'tt_tomli_LICENSE', 'awg_external.py', 'awg.py', 'awg_network.py', 'awg_contract.py', 'panel_update.py', 'panel_update_release.py', 'observed_inbounds.py', 'apt.py', 'panel_discovery.py', 'components.py', 'component_releases.py', 'runner.py', 'antirkn-runner.service', 'panel.py', 'panel_api.py', 'panel_release.py', 'vless.py', 'vless_contract.py']
if all((ROOT / 'server/runner' / p).exists() for p in paths):
    payload = {'contract.py': base64.b64encode(contract).decode()}
    for path in paths:
        payload[path] = base64.b64encode((ROOT / 'server/runner' / path).read_bytes()).decode()
    hashes = {p: hashlib.sha256(base64.b64decode(b)).hexdigest() for p, b in payload.items()}
    release = hashlib.sha256(json.dumps(hashes, sort_keys=True).encode()).hexdigest()
    command = next(line.removeprefix('ExecStart=') for line in (ROOT / 'server/runner/antirkn-runner.service').read_text().splitlines() if line.startswith('ExecStart='))
    if not command.endswith(' daemon'):
        raise SystemExit('Unexpected runner service command')
    rpc_command = command.removesuffix(' daemon') + ' rpc'
    bundle = json.dumps({'release': release, 'files': payload, 'hashes': hashes}, sort_keys=True)
    installer = (ROOT / 'server/runner/install.py').read_text()
    probe = (ROOT / 'server/runner/runner_inspect.py').read_text()
    import zlib
    predecessors_map = {}
    for i in range(1, 68):
        suffix = f'-v{i}' if i > 1 else ''
        schema_file = ROOT / f'schemas/runner-predecessor{suffix}.json'
        predecessors_map[f'v{i}'] = json.loads(schema_file.read_text())
    predecessors_blob = base64.b64encode(zlib.compress(json.dumps(predecessors_map, separators=(',', ':')).encode('utf-8'), 9)).decode('ascii')
    probe_unpack = (
        'import base64, json, zlib\n'
        f'_ALL_PREDECESSORS = json.loads(zlib.decompress(base64.b64decode("""{predecessors_blob}""")))\n'
        "globals().update({('PREDECESSOR' if v == 'v1' else f'PREDECESSOR_{v.upper()}'): d for v, d in _ALL_PREDECESSORS.items()})\n"
    )
    probe = probe_unpack + probe
    # The plan inspectors run as `python3 -I -c <source>` before the runner is
    # installed, so no sibling module is importable there. Their modules are
    # embedded unchanged and served by an in-memory importer placed first on
    # sys.meta_path: every import form (multi-line, aliased, inside a function)
    # resolves to the bundled code, and a missing module fails generation.
    import ast

    def module_source(name):
        generated = {'panel_release.py': release_source, 'component_releases.py': component_source}
        if name + '.py' in generated:
            return '# Generated by tool/generate_runner.py; do not edit.\n' + generated[name + '.py']
        return (ROOT / 'server/runner' / (name + '.py')).read_text()

    def sibling_imports(source):
        found = set()
        for node in ast.walk(ast.parse(source)):
            names = [node.module] if isinstance(node, ast.ImportFrom) and node.level == 0 else (
                [alias.name for alias in node.names] if isinstance(node, ast.Import) else [])
            found.update(n for n in names if n and (ROOT / 'server/runner' / (n + '.py')).exists())
        return found

    def embedded_inspector(modules, lazy, entry):
        """``modules`` are bundled; ``lazy`` are sibling imports made only by
        code the plan never runs (they stay unavailable and would fail)."""
        sources = {name: module_source(name) for name in modules}
        for name, source in sources.items():
            missing = sibling_imports(source) - set(sources) - set(lazy.get(name, ()))
            if missing:
                raise SystemExit(f'Inspector module {name} imports unbundled {sorted(missing)}')
        blob = base64.b64encode(zlib.compress(json.dumps(sources, sort_keys=True).encode(), 9)).decode('ascii')
        return (
            'import base64, importlib.abc, importlib.util, json, sys, zlib\n'
            'class _AntirknSources(importlib.abc.MetaPathFinder, importlib.abc.Loader):\n'
            '    def __init__(self, sources):\n'
            '        self.sources = sources\n'
            '    def find_spec(self, name, path=None, target=None):\n'
            '        return importlib.util.spec_from_loader(name, self) if name in self.sources else None\n'
            '    def create_module(self, spec):\n'
            '        return None\n'
            '    def exec_module(self, module):\n'
            "        exec(compile(self.sources[module.__name__], module.__name__ + '.py', 'exec'), module.__dict__)\n"
            f'sys.meta_path.insert(0, _AntirknSources(json.loads(zlib.decompress(base64.b64decode("""{blob}""")))))\n'
            + entry
            + "print('__ANTIRKN_RUNNER_INPUT__', file=sys.stderr, flush=True)\n"
            'req = json.loads(sys.stdin.buffer.read(4096))\n')

    panel_modules = ['panel', 'panel_release', 'sysutil']
    panel_lazy = {'panel': ['panel_api']}
    panel_probe = embedded_inspector(panel_modules, panel_lazy, 'from panel import panel_plan\n')
    panel_probe += "print(json.dumps(dict(version=1,code='ok',alive=False,jobs=[],panelPlan=panel_plan(req['port']))))\n"
    component_probe = embedded_inspector(panel_modules + ['components', 'component_releases'],
        dict(panel_lazy, components=['component_upgrade']), 'from components import component_plan\n')
    component_probe += "print(json.dumps(dict(version=1,code='ok',alive=False,jobs=[],componentPlan=component_plan(req['component'], req.get('payload') or None))))\n"
    for name, source in {'runner_inspect.py': probe, 'install.py': installer}.items():
        if sibling_imports(source):
            raise SystemExit(f'{name} runs standalone and must not import runner modules')
    if any("'''" in source for source in (probe, installer, panel_probe, component_probe)):
        raise SystemExit('Inspector source cannot be a Dart raw string')
    # Inspector is exactly the same source for client preview and root precondition.
    render('packages/ssh_transport/lib/src/runner_bundle.g.dart',
        '// Generated by tool/generate_runner.py; do not edit.\n'
        + 'const runnerRelease = ' + repr(release) + ';\n'
        + 'const runnerRpcCommand = ' + repr(rpc_command) + ';\n'
        + "const runnerBundle = r'''" + bundle + "''';\n"
        + "const runnerInspector = r'''" + probe + "''';\n"
        + "const runnerInstaller = r'''" + probe + '\n' + installer + "''';\n"
        + "const runnerComponentInspector = r'''" + component_probe + "''';\n"
        + "const runnerPanelInspector = r'''" + panel_probe + "''';\n")
print('Runner generated contracts/bundle: OK')
