#!/usr/bin/env python3
"""Generate the fixed wire layout and limits from the sync schema."""
import json
from pathlib import Path
import subprocess
import sys
import tempfile

root = Path(__file__).resolve().parent.parent
schema = json.loads((root / 'schemas/sync-packet-v1.json').read_text())
lines = ['// Generated by tool/generate_sync.py; do not edit.']
for field in ['version', 'magic', 'suite', 'keyBytes', 'nonceBytes',
              'tagBytes', 'maxPacketBytes', 'maxSourceBytes']:
    value = json.dumps(schema[field])
    lines.append(f'const sync{field[0].upper() + field[1:]} = {value};')
offset = 0
for field, width in schema['header']:
    lines.append(f'const sync{field[0].upper() + field[1:]}Offset = {offset};')
    offset += width
lines.append(f'const syncHeaderBytes = {offset};')
with tempfile.TemporaryDirectory() as directory:
    temporary = Path(directory) / 'contract.dart'
    temporary.write_text('\n'.join(lines) + '\n')
    subprocess.run(['dart', 'format', str(temporary)], check=True, capture_output=True)
    source = temporary.read_text()
target = root / 'packages/sync/lib/src/packet_contract.g.dart'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != source:
        raise SystemExit('Generated sync contract differs')
else:
    target.write_text(source)
print('Sync packet generated contract: OK')
